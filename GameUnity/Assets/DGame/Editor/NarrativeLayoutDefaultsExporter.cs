using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace DGame
{
	internal static class NarrativeLayoutDefaultsExporter
	{
		[Serializable]
		private sealed class SessionRows
		{
			public SessionRow[] rows;
		}

		[Serializable]
		private sealed class SessionRow
		{
			public string id;
			public string npcSet;
		}

		private const string PreferencePrefix = "NarrativeHudLayout.";
		private const string OutputPath = "Assets/Scripts/HotFix/GameLogic/UI/Battle/NarrativeLayoutDefaults.Generated.cs";

		[MenuItem("DGame Tools/剧情/将当前布局保存为打包默认布局")]
		private static void Export()
		{
			if (EditorApplication.isPlayingOrWillChangePlaymode)
			{
				EditorUtility.DisplayDialog("布局导出", "请先退出 PlayMode，再导出当前布局。", "确定");
				return;
			}

			var parts = new HashSet<string>(PlayerPrefs.GetString(PreferencePrefix + "Parts", string.Empty)
				.Split(new[] { '\n' }, StringSplitOptions.RemoveEmptyEntries));
			parts.Add("Items");
			parts.Add("Collection");
			parts.Add("LayoutEditButton");
			AddSessionCharacterParts(parts);
			var rows = new List<string>();
			foreach (string part in parts.OrderBy(value => value, StringComparer.Ordinal))
			{
				string key = PreferencePrefix + part;
				bool hasPosition = PlayerPrefs.HasKey(key + ".X") && PlayerPrefs.HasKey(key + ".Y");
				bool hasScale = PlayerPrefs.HasKey(key + ".Scale");
				bool hasLayer = PlayerPrefs.HasKey(key + ".Layer");
				bool hasMirror = PlayerPrefs.HasKey(key + ".Mirror");
				if (!hasPosition && !hasScale && !hasLayer && !hasMirror) continue;
				rows.Add("\t\t\tentries.Add(" + Quote(part) + ", new Entry(" +
					Bool(hasPosition) + ", " + Float(PlayerPrefs.GetFloat(key + ".X")) + ", " +
					Float(PlayerPrefs.GetFloat(key + ".Y")) + ", " + Bool(hasScale) + ", " +
					Float(PlayerPrefs.GetFloat(key + ".Scale", 1f)) + ", " + Bool(hasLayer) + ", " +
					PlayerPrefs.GetInt(key + ".Layer", 0) + ", " + Bool(hasMirror) + ", " +
					Bool(PlayerPrefs.GetInt(key + ".Mirror", 0) != 0) + "));");
			}

			string source = "// Generated by DGame Tools/剧情/将当前布局保存为打包默认布局.\n" +
				"using System.Collections.Generic;\n\nnamespace GameLogic\n{\n" +
				"\tinternal static partial class NarrativeLayoutDefaults\n\t{\n" +
				"\t\tstatic partial void AddGeneratedEntries(Dictionary<string, Entry> entries)\n\t\t{\n" +
				string.Join("\n", rows) + (rows.Count > 0 ? "\n" : string.Empty) +
				"\t\t}\n\t}\n}\n";
			string absolutePath = Path.Combine(Application.dataPath, OutputPath.Substring("Assets/".Length));
			if (!File.Exists(absolutePath) || File.ReadAllText(absolutePath) != source)
			{
				File.WriteAllText(absolutePath, source, new UTF8Encoding(false));
				AssetDatabase.ImportAsset(OutputPath);
			}
			Debug.Log($"剧情默认布局已导出：{rows.Count} 项，{OutputPath}。打包前请提交该文件并重新生成 GameLogic DLL。");
		}

		private static void AddSessionCharacterParts(HashSet<string> parts)
		{
			string projectPath = Directory.GetParent(Application.dataPath).FullName;
			string sessionsPath = Path.Combine(projectPath, "Configs/Json/tbnarrativesessionconfig.json");
			if (!File.Exists(sessionsPath)) return;
			var sessions = JsonUtility.FromJson<SessionRows>("{\"rows\":" + File.ReadAllText(sessionsPath) + "}");
			if (sessions?.rows == null) return;
			foreach (SessionRow session in sessions.rows)
			{
				if (string.IsNullOrWhiteSpace(session.id) || string.IsNullOrWhiteSpace(session.npcSet)) continue;
				foreach (string name in session.npcSet.Split(new[] { ',', '，', '、' }, StringSplitOptions.RemoveEmptyEntries))
				{
					string npcId = name.Trim();
					if (npcId.Length == 0) continue;
					parts.Add("Character." + session.id + ".NpcDialogue." + npcId);
					parts.Add("Character." + session.id + ".PlayerDialogue." + npcId);
				}
			}
		}

		private static string Bool(bool value) => value ? "true" : "false";
		private static string Float(float value) => value.ToString("R", CultureInfo.InvariantCulture) + "f";
		private static string Quote(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
	}
}
